def available_formations() -> List[str]:
    return sorted(FORMATION_TEMPLATES.keys())

def parse_formation(s: str) -> str:
    if not isinstance(s, str) or not s.strip():
        return DEFAULT_FORMATION
    s = s.strip().replace(" ", "")
    return s if s in FORMATION_TEMPLATES else DEFAULT_FORMATION

def coords_team1(formation: str) -> List[Tuple[int, int]]:
    return FORMATION_TEMPLATES[parse_formation(formation)]

def coords_team2(formation: str, cfg: SimulationConfig) -> List[Tuple[int, int]]:
    coords = coords_team1(formation)
    mirror = lambda x: (cfg.x_min + cfg.x_max) - x
    return [(mirror(x), y) for x, y in coords]
